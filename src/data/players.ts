const slugify = (value: string) =>
  value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .toLowerCase();

const hashString = (value: string) =>
  Array.from(value).reduce((accumulator, character, index) => {
    return accumulator + character.charCodeAt(0) * (index + 7);
  }, 0);

